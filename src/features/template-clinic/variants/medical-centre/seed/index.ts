// The starting point of the demo: also what "Reset demo" restores (the account is kept by the engine).
export function createMedicalCentreSeed(now: Date): ClinicData {
  return {
    account: null,
    settings: seedSettings,
    content: seedContent,
    doctors: seedDoctors,
    departments: seedDepartments,
    treatments: seedTreatments,
    appointments: buildAppointments(specs, now),
    results: seedResults,
    faqs: seedFaqs,
    testimonials: seedTestimonials,
    dismissedTips: [],
  };
}
